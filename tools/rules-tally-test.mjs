import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,setDoc,getDoc,updateDoc,deleteDoc,writeBatch,increment} from 'firebase/firestore';
import fs from 'fs';
const env=await initializeTestEnvironment({projectId:'demo-banee',firestore:{rules:fs.readFileSync('firestore.rules','utf8'),host:'127.0.0.1',port:8787}});
const now=Date.now();
await env.withSecurityRulesDisabled(async c=>{const d=c.firestore();
 await setDoc(doc(d,'apps/A'),{owner:'own',modes:{bookings:'private',members:'private'},updatedAt:now,first:{bookings:'new'},roleAccess:{bookings:['manager']}});
 await setDoc(doc(d,'apps/A/members/mgr'),{role:'manager',status:'ok',userId:'mgr'});
 await setDoc(doc(d,'apps/A/bookings/old'),{userId:'cus',status:'new',slotId:'s9',amount:50});
 await setDoc(doc(d,'apps/A/_tally/bookings__slotId__s9'),{n:1,amount:50});
});
const db=u=>env.authenticatedContext(u).firestore();
const T=[];const ok=async(n,p)=>{await assertSucceeds(p).then(()=>console.log('✓ مسموح:',n),e=>{console.log('✗ خطأ (كان يجب أن يُسمح):',n,e.code);process.exitCode=1})};
const no=async(n,p)=>{await assertFails(p).then(()=>console.log('✓ ممنوع:',n),e=>{console.log('✗ ثغرة (كان يجب أن يُمنع):',n);process.exitCode=1})};
const tl=(d,slot)=>doc(d,'apps/A/_tally/bookings__slotId__'+slot);
const T1=(slot,ref,n,a)=>({n:increment(n),amount:increment(a||0),ref:'bookings/'+ref,k:'slotId',v:slot});
let d=db('cus'),b;
await no('زيادة العدّاد بلا حجز حقيقي',setDoc(tl(d,'s1'),T1('s1','ghost',1),{merge:true}));
await no('زيادة العدّاد بالصيغة القديمة (بلا مرجع)',setDoc(tl(d,'s1'),{n:1,amount:0}));
b=writeBatch(d);b.set(doc(d,'apps/A/bookings/k1'),{userId:'cus',status:'new',slotId:'s1',amount:100});b.set(tl(d,'s1'),T1('s1','k1',1,100),{merge:true});
await ok('حجز حقيقي + عدّاد في عملية واحدة',b.commit());
await no('زيادة ثانية لنفس الحجز الموجود',setDoc(tl(d,'s1'),T1('s1','k1',1),{merge:true}));
await no('استعمال حجز حقيقي لزيادة عدّاد موعد آخر',setDoc(tl(d,'s2'),T1('s2','k1',1),{merge:true}));
await no('إنقاص عدّاد حجز ما زال قائماً',setDoc(tl(d,'s1'),T1('s1','k1',-1,-100),{merge:true}));
b=writeBatch(d);b.set(doc(d,'apps/A/bookings/k2'),{userId:'cus',status:'new',slotId:'s3',amount:10});b.set(tl(d,'s3'),T1('s3','k2',1,10),{merge:true});b.update(tl(d,'s3'),{n:increment(1)});
await no('حجز واحد وزيادتان في نفس العملية',b.commit());
b=writeBatch(d);b.set(doc(d,'apps/A/bookings/k3'),{userId:'cus',status:'new',slotId:'s4',amount:10});b.set(tl(d,'s4'),T1('s4','k3',1,9999),{merge:true});
await no('مبلغ مزوّر في العدّاد',b.commit());
b=writeBatch(d);b.update(doc(d,'apps/A/bookings/k1'),{status:'cancelled'});b.set(tl(d,'s1'),T1('s1','k1',-1,-100),{merge:true});
await ok('إلغاء الحجز + إنقاص العدّاد',b.commit());
console.log('  العدّاد بعد الإلغاء:',JSON.stringify((await getDoc(tl(d,'s1'))).data().n));
const m=db('mgr');b=writeBatch(m);b.update(doc(m,'apps/A/bookings/old'),{status:'cancelled'});b.set(tl(m,'s9'),T1('s9','old',-1,-50),{merge:true});
await ok('المدير يلغي حجز زبون + إنقاص',b.commit());
b=writeBatch(d);b.delete(doc(d,'apps/A/bookings/k1'));
await ok('حذف حجز ملغى بلا تغيير العدّاد',b.commit());
await ok('قراءة العدّاد لأي مسجّل',getDoc(tl(db('x'),'s1')));
await env.cleanup();
