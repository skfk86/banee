// npx firebase emulators:exec --project demo-banee --only firestore "node tools/rules-test.mjs"  (المنفذ 8787 في firebase.json للمحاكي)
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,setDoc,getDoc,updateDoc,deleteDoc} from 'firebase/firestore';
import fs from 'fs';
const env=await initializeTestEnvironment({projectId:'demo-banee',firestore:{rules:fs.readFileSync('firestore.rules','utf8'),host:'127.0.0.1',port:8787}});
const now=Date.now();
await env.withSecurityRulesDisabled(async c=>{const d=c.firestore();
 await setDoc(doc(d,'apps/A'),{owner:'own',modes:{services:'content',bookings:'private',members:'private',notes:'private',chat:'shared'},updatedAt:now,first:{bookings:'new'},roleAccess:{bookings:['manager']},roleApprove:['manager']});
 await setDoc(doc(d,'apps/A/members/mgr'),{role:'manager',status:'ok',userId:'mgr'});
 await setDoc(doc(d,'apps/A/bookings/b1'),{userId:'cus',status:'new',price:100});
 await setDoc(doc(d,'apps/A/bookings/b2'),{userId:'other',status:'new',price:50});
 await setDoc(doc(d,'apps/A/services/s1'),{title:'x'});
 await setDoc(doc(d,'apps/OLD'),{owner:'own',modes:{bookings:'private'},updatedAt:now-40*864e5});
 await setDoc(doc(d,'apps/OLD/bookings/b'),{userId:'cus',status:'new'});
 await setDoc(doc(d,'users/cus'),{plan:'free'});
 await setDoc(doc(d,'live/L'),{owner:'own',v:5});
});
const db=u=>(u?env.authenticatedContext(u):env.unauthenticatedContext()).firestore();
const T=[];const ok=(n,p)=>T.push(assertSucceeds(p).then(()=>console.log('✓ مسموح:',n),e=>{console.log('✗ خطأ (كان يجب أن يُسمح):',n,e.code);process.exitCode=1}));
const no=(n,p)=>T.push(assertFails(p).then(()=>console.log('✓ ممنوع:',n),e=>{console.log('✗ ثغرة (كان يجب أن يُمنع):',n);process.exitCode=1}));
ok('زائر يقرأ الخدمات',getDoc(doc(db(),'apps/A/services/s1')));
no('زبون يعدّل خدمة',setDoc(doc(db('cus'),'apps/A/services/s1'),{title:'h'}));
ok('زبون ينشئ حجزاً بحالة new',setDoc(doc(db('cus'),'apps/A/bookings/n1'),{userId:'cus',status:'new',price:100}));
no('زبون ينشئ حجزاً بحالة done',setDoc(doc(db('cus'),'apps/A/bookings/n2'),{userId:'cus',status:'done',price:100}));
no('زبون ينشئ حجزاً باسم غيره',setDoc(doc(db('cus'),'apps/A/bookings/n3'),{userId:'other',status:'new'}));
ok('زبون يقرأ حجزه',getDoc(doc(db('cus'),'apps/A/bookings/b1')));
no('زبون يقرأ حجز غيره',getDoc(doc(db('cus'),'apps/A/bookings/b2')));
ok('زبون يلغي حجزه',updateDoc(doc(db('cus'),'apps/A/bookings/b1'),{status:'cancelled'}));
no('زبون يغيّر سعر حجزه',updateDoc(doc(db('cus'),'apps/A/bookings/b1'),{price:1}));
no('زبون يعدّل حجز غيره',updateDoc(doc(db('cus'),'apps/A/bookings/b2'),{status:'cancelled'}));
ok('المدير يقرأ حجز زبون',getDoc(doc(db('mgr'),'apps/A/bookings/b2')));
ok('المدير يؤكد حجزاً',updateDoc(doc(db('mgr'),'apps/A/bookings/b2'),{status:'confirmed'}));
no('زبون يمنح نفسه دور المدير',setDoc(doc(db('cus'),'apps/A/members/cus'),{role:'manager',status:'ok',userId:'cus'}));
ok('زبون يطلب دور المدير (قيد المراجعة)',setDoc(doc(db('cus'),'apps/A/members/cus'),{role:'manager',status:'pending',userId:'cus'}));
ok('صاحب التطبيق يكتب أي شيء',setDoc(doc(db('own'),'apps/A/services/s2'),{title:'y'}));
ok('مجموعة بلا حالات: إنشاء عادي',setDoc(doc(db('cus'),'apps/A/notes/x'),{userId:'cus',text:'a'}));
no('تطبيق تجريبي متوقف ٤٠ يوماً: قراءة',getDoc(doc(db('cus'),'apps/OLD/bookings/b')));
no('غير المالك يغيّر مالك التطبيق',updateDoc(doc(db('cus'),'apps/A'),{owner:'cus'}));
no('استضافة أكثر من ٤٠٠ يوم',updateDoc(doc(db('own'),'apps/A'),{hostUntil:now+500*864e5}));
no('مستخدم يرقّي خطته بنفسه',updateDoc(doc(db('cus'),'users/cus'),{plan:'business'}));
no('قراءة حساب مستخدم آخر',getDoc(doc(db('other'),'users/cus')));
no('غير المالك ينشر تحديثاً حياً',updateDoc(doc(db('cus'),'live/L'),{v:9}));
no('المالك يُنقص رقم النسخة الحية',updateDoc(doc(db('own'),'live/L'),{v:1}));
no('مجموعة غير معروفة في الجذر',setDoc(doc(db('cus'),'secret/x'),{a:1}));
await Promise.all(T);await env.cleanup();
